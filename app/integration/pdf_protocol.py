"""Сборка минимального PDF-протокола осмотра без внешних библиотек."""

from __future__ import annotations

from datetime import datetime
from typing import Sequence

from app.domain.entities import AccidentClaim, Inspection

_TRANSLIT_LOWER = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e",
    "ж": "zh", "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "kh", "ц": "ts", "ч": "ch", "ш": "sh", "щ": "shch",
    "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
}
_TRANSLIT = {**_TRANSLIT_LOWER, **{k.upper(): v.upper() for k, v in _TRANSLIT_LOWER.items()}}


def _translit(text: str) -> str:
    return "".join(_TRANSLIT.get(char, char) for char in text)


def _escape_pdf(text: str) -> str:
    return _translit(text).replace("\\", r"\\").replace("(", r"\(").replace(")", r"\)")


def _wrap_pdf(objects: Sequence[bytes]) -> bytes:
    out = bytearray(b"%PDF-1.4\n")
    offsets: list[int] = []
    for index, obj in enumerate(objects, start=1):
        offsets.append(len(out))
        out += f"{index} 0 obj\n".encode("ascii") + obj + b"\nendobj\n"
    xref_pos = len(out)
    out += f"xref\n0 {len(objects) + 1}\n".encode("ascii")
    out += b"0000000000 65535 f \n"
    for offset in offsets:
        out += f"{offset:010d} 00000 n \n".encode("ascii")
    out += f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\nstartxref\n{xref_pos}\n%%EOF\n".encode("ascii")
    return bytes(out)


def build_protocol_pdf(claim: AccidentClaim, inspection: Inspection | None, photos_count: int) -> bytes:
    damage = "YES" if inspection is not None and inspection.damage_found else "NO"
    lines = [
        "OSAGO ACCIDENT PROTOCOL",
        "",
        f"Claim number : {claim.number}",
        f"Claim id     : {claim.claim_id}",
        f"Policy       : {claim.policy_number} (valid)",
        f"Region       : {claim.region}",
        f"Description  : {claim.description}",
        "",
        f"Damage found : {damage}",
        f"Expert notes : {inspection.notes if inspection else ''}",
        f"Photos attached : {photos_count}",
        "",
        f"Status       : {claim.status.value}",
        f"Created at   : {datetime.now().isoformat(timespec='seconds')} (demo worker)",
        "",
        "This protocol was generated by the demo worker of the OSAGO IS API.",
    ]
    stream = "BT /F1 12 Tf 50 790 Td 16 TL " + " ".join(
        f"({_escape_pdf(line)}) Tj T*" for line in lines
    ) + " ET"
    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>",
        f"<< /Length {len(stream)} >>\nstream\n{stream}\nendstream".encode("ascii"),
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    ]
    return _wrap_pdf(objects)
